// Package deviceenrollment 实现基于一次性挑战的设备注册与密钥生命周期管理服务。
//
// 核心能力：
//   - 管理员签发短期、绑定预期设备属性的一次性注册挑战，明文秘密不落盘；
//   - 设备凭公钥与证明完成注册，支持幂等重放与同号异内容冲突检测；
//   - 注册后的密钥轮换（旧/新钥双确认、取消、超时），终态唯一、旧钥即时失效；
//   - 绑定当前密钥版本的认证校验，旧版本迟到请求不能覆盖新状态；
//   - 管理员禁用设备，原子终止注册有效性与全部待处理轮换。
//
// 所有过期判断都经由可替换的 Clock；所有状态变更在同一互斥临界区内作用于快照并原子落盘。
// HTTP 接口见 Handler。
